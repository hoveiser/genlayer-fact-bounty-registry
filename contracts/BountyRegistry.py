class BountyRegistry(gl.Contract):
    """Accepts bounty creation, deploys one `BountyClaim` per bounty, indexes them."""

    owner: Address
    bounty_index: TreeMap[str, Address]
    bounty_ids: DynArray[str]
    next_nonce: u256
    total_created: u256

    def __init__(self) -> None:
        self.owner = gl.message.sender_address
        self.next_nonce = u256(1)
        self.total_created = u256(0)

    # ------------------------------------------------------------------
    # Public writes
    # ------------------------------------------------------------------
    @gl.public.write.payable
    def create_bounty(
        self,
        bounty_id: str,
        repo_full_name: str,
        threshold: u256,
        deadline_at: str,
    ) -> Address:
        """Lock the attached GEN value as a reward and deploy a child for the claim.

        Payable: the reward is the native value carried by this very call, so the
        escrow cannot exceed what the poster actually paid.
        """
        reward = u256(int(gl.message.value))
        if reward <= 0:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} create_bounty must attach a positive GEN reward")

        identifier = str(bounty_id).strip()
        if not identifier:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bounty_id must not be empty")
        if " " in identifier:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bounty_id must not contain spaces")
        if identifier in self.bounty_index:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bounty_id '{identifier}' already exists")

        poster = gl.message.sender_address
        child_address = gl.deploy_contract(
            code=bytes.fromhex(_CHILD_SOURCE_HEX),
            args=[
                identifier,
                repo_full_name,
                u256(int(threshold)),
                deadline_at,
                poster,
                reward,
                gl.message.contract_address,
            ],
            salt_nonce=self.next_nonce,
            value=reward,
            on="finalized",
        )

        self.next_nonce = u256(int(self.next_nonce) + 1)
        self.total_created = u256(int(self.total_created) + 1)
        self.bounty_index[identifier] = child_address
        self.bounty_ids.append(identifier)
        return child_address

    @gl.public.write
    def set_owner(self, new_owner: Address) -> None:
        """Transfer registry ownership. Append-only administrative method."""
        if gl.message.sender_address.as_hex != self.owner.as_hex:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} only the owner may reassign ownership")
        self.owner = new_owner

    # ------------------------------------------------------------------
    # Views
    # ------------------------------------------------------------------
    @gl.public.view
    def list_bounties(self) -> dict:
        """Enumeration view over every bounty ever created."""
        entries: list = []
        for identifier in self.bounty_ids:
            entries.append(
                {
                    "bounty_id": identifier,
                    "address": self.bounty_index[identifier].as_hex,
                }
            )
        return {
            "count": len(entries),
            "total_created": int(self.total_created),
            "bounties": entries,
        }

    @gl.public.view
    def get_bounty_address(self, bounty_id: str) -> str:
        if bounty_id not in self.bounty_index:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} unknown bounty_id '{bounty_id}'")
        return self.bounty_index[bounty_id].as_hex

    @gl.public.view
    def get_bounty_status(self, bounty_id: str) -> dict:
        """Delegate a single bounty read to its child contract."""
        if bounty_id not in self.bounty_index:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} unknown bounty_id '{bounty_id}'")
        child = gl.get_contract_at(self.bounty_index[bounty_id])
        return child.view().get_status()

    @gl.public.view
    def aggregate_statuses(self) -> dict:
        """Synchronously read every child to build a registry-wide roll-up.

        Demonstrates the parent reading from its children in one view call. The
        per-child reads are plain synchronous cross-contract view calls, so the
        roll-up always reflects the children as the source of truth rather than a
        copy the parent has to keep in sync.
        """
        by_status: dict = {}
        children: list = []
        escrow_atto = 0
        for identifier in self.bounty_ids:
            child = gl.get_contract_at(self.bounty_index[identifier])
            try:
                status = child.view().get_status()
            except Exception:
                # Child not deployed yet, or already self-destructed: report it as
                # unreadable rather than pretending the bounty vanished.
                by_status["UNREADABLE"] = int(by_status.get("UNREADABLE", 0)) + 1
                continue
            state = str(status["status"])
            by_status[state] = int(by_status.get(state, 0)) + 1
            escrow_atto += int(status["escrow_atto"])
            children.append(
                {
                    "bounty_id": identifier,
                    "address": self.bounty_index[identifier].as_hex,
                    "status": state,
                    "reported_verdict": str(status["reported_verdict"]),
                    "truth_verdict": str(status["truth_verdict"]),
                    "escrow_atto": int(status["escrow_atto"]),
                }
            )
        return {
            "bounty_count": len(self.bounty_ids),
            "escrow_total_atto": escrow_atto,
            "by_status": by_status,
            "bounties": children,
        }
