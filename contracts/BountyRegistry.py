class BountyRegistry(gl.Contract):
    """Accepts bounty creation, deploys one `BountyClaim` per bounty, indexes them."""

    owner: Address
    bounty_index: TreeMap[str, Address]
    bounty_ids: DynArray[str]
    next_nonce: u256
    total_created: u256

    def __init__(self) -> None:
        self.owner = gl.message.sender_address
        self.next_nonce = u256(1)
        self.total_created = u256(0)

    # ------------------------------------------------------------------
    # Public writes
    # ------------------------------------------------------------------
    @gl.public.write.payable
    def create_bounty(
        self,
        bounty_id: str,
        repo_full_name: str,
        threshold: u256,
        deadline_at: str,
    ) -> Address:
        """Lock the attached GEN value as a reward and deploy a child for the claim.

        Payable: the reward is the native value carried by this very call, so the
        escrow cannot exceed what the poster actually paid.

        Every claim input is validated *here*, before the child deployment is
        scheduled: an unresolvable repository, a threshold of zero, or a deadline
        that is malformed or already past cannot ever reach a verdict, so they
        revert with the escrow untouched and no child contract created. The
        `finalized` child deploy only ever runs for a well-formed, live claim.
        """
        reward = u256(int(gl.message.value))
        if reward <= 0:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} create_bounty must attach a positive GEN reward")

        identifier = str(bounty_id).strip()
        if not identifier:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bounty_id must not be empty")
        if " " in identifier:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bounty_id must not contain spaces")
        if identifier in self.bounty_index:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bounty_id '{identifier}' already exists")

        repo = str(repo_full_name).strip().lower()
        if not _valid_repo_shape(repo):
            raise gl.vm.UserError(
                f"{ERROR_EXPECTED} repo_full_name must look like 'owner/name', got '{repo_full_name}'"
            )
        if int(threshold) <= 0:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} threshold must be positive")
        if not _valid_datetime(deadline_at):
            raise gl.vm.UserError(
                f"{ERROR_EXPECTED} deadline_at must be 'YYYY-MM-DDTHH:MM:SS' UTC, got '{deadline_at}'"
            )
        now = _normalize_datetime(gl.message_raw["datetime"])
        if _normalize_datetime(deadline_at) <= now:
            raise gl.vm.UserError(
                f"{ERROR_EXPECTED} deadline_at must be in the future: {deadline_at} has already "
                f"passed or equals now ({now})"
            )

        poster = gl.message.sender_address
        child_address = gl.deploy_contract(
            code=bytes.fromhex(_CHILD_SOURCE_HEX),
            args=[
                identifier,
                repo_full_name,
                u256(int(threshold)),
                deadline_at,
                poster,
                reward,
                gl.message.contract_address,
            ],
            salt_nonce=self.next_nonce,
            value=reward,
            on="finalized",
        )

        self.next_nonce = u256(int(self.next_nonce) + 1)
        self.total_created = u256(int(self.total_created) + 1)
        self.bounty_index[identifier] = child_address
        self.bounty_ids.append(identifier)
        return child_address

    @gl.public.write
    def set_owner(self, new_owner: Address) -> None:
        """Transfer registry ownership. Append-only administrative method."""
        if gl.message.sender_address.as_hex != self.owner.as_hex:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} only the owner may reassign ownership")
        self.owner = new_owner

