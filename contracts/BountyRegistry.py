"""Factory + index contract for the fact-check bounty registry.

A poster calls `create_bounty` with a checkable claim and locks a GEN reward;
the registry deploys a dedicated `BountyClaim` child through the SDK's
contract-deploy primitive and remembers it in a `TreeMap[str, Address]`.

Why a factory here
------------------
Every bounty carries its own appealable, non-deterministic verification
state machine and its own escrow. One shared contract would have to keep N
independent escrows and N verification state machines in one layout, so a bug
or an appeal in one bounty is a bug in all of them. Deploying one child per
bounty gives isolation by construction: a child can only ever move the GEN it
holds itself, and the child address is the bounty's receipt.

Child source transport
----------------------
The single-file `py-genlayer` runner maps exactly one uploaded file to
`/contract.py`, so the documented `open("/contract/BountyClaim.py")` factory
idiom needs the `py-genlayer-multi` runner, which the deployed `genlayer` CLI
cannot package. The child source is therefore embedded in this file as a hex
constant and handed to `gl.deploy_contract` as bytes. `scripts/build_bundle.py`
regenerates the block below from `contracts/BountyClaim.py`, and a direct-mode
test asserts the embedded copy still equals the canonical file, so the two
cannot silently drift.
"""

